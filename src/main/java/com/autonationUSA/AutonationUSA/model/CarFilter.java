package com.autonationUSA.AutonationUSA.model;

public class CarFilter {
	
	private String manufacturer;
	private String model;
	private double price;
	private int odometeReading;
	private int year;
	public String getManufacturer() {
		return manufacturer;
	}
	public void setManufacturer(String manufacturer) {
		this.manufacturer = manufacturer;
	}
	public String getModel() {
		return model;
	}
	public void setModel(String model) {
		this.model = model;
	}
	public double getPrice() {
		return price;
	}
	public void setPrice(double price) {
		this.price = price;
	}
	public int getOdometeReading() {
		return odometeReading;
	}
	public void setOdometeReading(int odometeReading) {
		this.odometeReading = odometeReading;
	}
	public int getYear() {
		return year;
	}
	public void setYear(int year) {
		this.year = year;
	}
	
	
	

}
